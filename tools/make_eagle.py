#!/usr/bin/env python3
"""Builds the Air browser's eagle from tools/eagle_shapes.py: the small Air icon (tabs, app
windows) and the SVG logo used inside the PC and on the new tab page. Run from the repository root.
(AirCursor and AirCursor PC use the arrow logo: tools/make_logo.py.)"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from eagle_shapes import shapes  # noqa: E402

RES = "app/src/main/res/drawable"
HEAD = ('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/make_eagle.py -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"\n'
        '    android:width="{w}dp" android:height="{w}dp" android:viewportWidth="108" android:viewportHeight="108">\n')
THEMES = {
    "aircursor": ("#FF23287F", "#FF4A33C4", "#FF8A3DE4"),   # indigo → violet
    "pc": ("#FF0B2A6F", "#FF1D5FD1", "#FF22A6E8"),          # deep blue → sky (AirCursor PC)
    "air": ("#FF1749B8", "#FF4E5BF0", "#FF9A5CF5"),         # Air browser
}


def path(pts):
    return "M" + " L".join("%.2f,%.2f" % p for p in pts) + "Z"


def argb(c, alpha="FF"):
    return "#" + alpha + c.lstrip("#").upper()


def bg_paths(theme, rounded):
    a, b, c = THEMES[theme]
    shape = ("M24,0h60a24,24 0 0 1 24,24v60a24,24 0 0 1 -24,24h-60a24,24 0 0 1 -24,-24v-60a24,24 0 0 1 24,-24z"
             if rounded else "M0,0h108v108h-108z")
    return (
        '<path android:pathData="%s"><aapt:attr name="android:fillColor"><gradient android:type="linear" '
        'android:startX="0" android:startY="0" android:endX="108" android:endY="108">'
        '<item android:offset="0" android:color="%s"/><item android:offset="0.55" android:color="%s"/>'
        '<item android:offset="1" android:color="%s"/></gradient></aapt:attr></path>\n'
        '<path android:pathData="%s"><aapt:attr name="android:fillColor"><gradient android:type="radial" '
        'android:centerX="32" android:centerY="30" android:gradientRadius="66">'
        '<item android:offset="0" android:color="#609DB3FF"/><item android:offset="1" android:color="#009DB3FF"/>'
        '</gradient></aapt:attr></path>\n' % (shape, a, b, c, shape))


GOLD = {"#FFD873", "#F7BE45", "#EBA035", "#D9852A", "#B86A17", "#CF7D22", "#8E4E12", "#E3962E", "#B5661A"}


def eagle_paths(scale, mono=False):
    out = []
    for i, (color, pts) in enumerate(shapes(scale)):
        # The monochrome (themed) icon: the head silhouette and the beak only, in one colour.
        if mono and i > 0 and color.upper() not in GOLD:
            continue
        col = "#FFFFFFFF" if mono else argb(color)
        out.append('<path android:pathData="%s" android:fillColor="%s" android:strokeColor="%s" '
                   'android:strokeWidth="0.35" android:strokeLineJoin="round"/>\n' % (path(pts), col, col))
    return "".join(out)


def write(name, body, w=108):
    with open(os.path.join(RES, name + ".xml"), "w") as f:
        f.write(HEAD.format(w=w) + body + "</vector>\n")


def svg(theme, scale=1.0, rounded=True):
    a, b, c = (x.replace("#FF", "#") for x in THEMES[theme])
    r = ' rx="24"' if rounded else ""
    parts = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="256" height="256">'
             '<defs><linearGradient id="bg" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="%s"/>'
             '<stop offset="0.55" stop-color="%s"/><stop offset="1" stop-color="%s"/></linearGradient>'
             '<radialGradient id="glow" cx="0.3" cy="0.28" r="0.62"><stop offset="0" stop-color="#9DB3FF" stop-opacity="0.38"/>'
             '<stop offset="1" stop-color="#9DB3FF" stop-opacity="0"/></radialGradient></defs>' % (a, b, c),
             '<rect width="108" height="108"%s fill="url(#bg)"/><rect width="108" height="108"%s fill="url(#glow)"/>' % (r, r)]
    for color, pts in shapes(scale):
        d = " ".join("%.2f,%.2f" % p for p in pts)
        parts.append('<polygon points="%s" fill="%s" stroke="%s" stroke-width="0.35" stroke-linejoin="round"/>' % (d, color, color))
    parts.append("</svg>\n")
    return "".join(parts)


def svg_bare(scale=1.0, pad=4.0):
    """The eagle alone (no tile): the PC's start button, so it differs from the Air app icon."""
    shp = shapes(scale)
    xs = [x for _, pts in shp for x, _ in pts]
    ys = [y for _, pts in shp for _, y in pts]
    x0, y0, x1, y1 = min(xs) - pad, min(ys) - pad, max(xs) + pad, max(ys) + pad
    side = max(x1 - x0, y1 - y0)
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    parts = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="%.2f %.2f %.2f %.2f" width="256" height="256">'
             % (cx - side / 2, cy - side / 2, side, side)]
    for color, pts in shp:
        d = " ".join("%.2f,%.2f" % p for p in pts)
        parts.append('<polygon points="%s" fill="%s" stroke="%s" stroke-width="0.35" stroke-linejoin="round"/>' % (d, color, color))
    parts.append("</svg>\n")
    return "".join(parts)


def main():
    write("ic_air_eagle", eagle_paths(1.15), w=24)
    os.makedirs("ubuntu", exist_ok=True)
    with open("ubuntu/air-logo.svg", "w") as f:
        f.write(svg("air"))
    print("eagle logos written")


if __name__ == "__main__":
    main()
