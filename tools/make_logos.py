#!/usr/bin/env python3
"""AirCursor brand logos -> adaptive launcher icons (background + foreground + monochrome),
full logos for use inside the app, and an HTML preview. Run: python3 tools/make_logos.py [preview.html]"""
import os, sys

ARROW = "M48,36L48,71.7L56.4,63.3L62.7,77L68.2,74.6L62.1,61.2L73.2,61.2Z"
WAVES = [("M37,36a11,11 0 0 1 11,-11", "0.85"), ("M30,36a18,18 0 0 1 18,-18", "0.5")]
PC_BODY = "M33,33h42a4,4 0 0 1 4,4v26a4,4 0 0 1 -4,4h-42a4,4 0 0 1 -4,-4v-26a4,4 0 0 1 4,-4z"
PC_SCREEN = "M35,37h38v24h-38z"
PC_STAND = "M50,67h8v6h-8z M42,73h24a2,2 0 0 1 2,2v1h-28v-1a2,2 0 0 1 2,-2z"
PC_ARROW = "M53,41L53,57.5L56.9,53.6L59.8,59.9L62.3,58.8L59.5,52.7L64.6,52.7Z"

BRAND = {
    "aircursor": ("#FF4338CA", "#FF7C3AED"),
    "pc": ("#FF0284C7", "#FF4338CA"),
}

def grad(c1, c2, x1=0, y1=0, x2=108, y2=108):
    return (f'<aapt:attr name="android:fillColor"><gradient android:type="linear" android:startX="{x1}" '
            f'android:startY="{y1}" android:endX="{x2}" android:endY="{y2}">'
            f'<item android:offset="0" android:color="{c1}"/><item android:offset="1" android:color="{c2}"/>'
            '</gradient></aapt:attr>')

def head(w=108):
    return ('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/make_logos.py -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android" '
            'xmlns:aapt="http://schemas.android.com/aapt"\n'
            f'    android:width="{w}dp" android:height="{w}dp" android:viewportWidth="108" android:viewportHeight="108">\n')

def fg(kind, mono=False):
    shadow = "#FF000000" if mono else "#59312E81"
    out = []
    if kind == "aircursor":
        for d, a in WAVES:
            out.append(f'<path android:pathData="{d}" android:strokeColor="#FFFFFFFF" android:strokeAlpha="{a}" '
                       'android:strokeWidth="4" android:strokeLineCap="round"/>')
        if not mono:
            out.append(f'<group android:translateX="1.6" android:translateY="2.2"><path android:pathData="{ARROW}" '
                       f'android:fillColor="{shadow}" android:strokeColor="{shadow}" android:strokeWidth="3" '
                       'android:strokeLineJoin="round"/></group>')
        out.append(f'<path android:pathData="{ARROW}" android:fillColor="#FFFFFFFF" android:strokeColor="#FFFFFFFF" '
                   'android:strokeWidth="3" android:strokeLineJoin="round"/>')
    else:
        out.append(f'<path android:pathData="{PC_BODY}" android:fillColor="#FFFFFFFF"/>')
        out.append(f'<path android:pathData="{PC_SCREEN}" android:fillColor="{"#FF000000" if mono else "#FF1E1B4B"}"/>')
        out.append(f'<path android:pathData="{PC_STAND}" android:fillColor="#FFFFFFFF"/>')
        out.append(f'<path android:pathData="{PC_ARROW}" android:fillColor="#FFFFFFFF" android:strokeColor="#FFFFFFFF" '
                   'android:strokeWidth="1.6" android:strokeLineJoin="round"/>')
    return "\n".join(out)

res = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "app", "src", "main", "res")
def write(rel, text):
    p = os.path.join(res, rel); os.makedirs(os.path.dirname(p), exist_ok=True); open(p, "w").write(text)

for kind, (c1, c2) in BRAND.items():
    write(f"drawable/brand_{kind}_bg.xml", head() + f'<path android:pathData="M0,0h108v108h-108z">{grad(c1, c2)}</path>\n'
          '<path android:pathData="M108,0v60a80,80 0 0 1 -80,-60z" android:fillColor="#14FFFFFF"/>\n</vector>\n')
    write(f"drawable/brand_{kind}_fg.xml", head() + fg(kind) + "\n</vector>\n")
    write(f"drawable/brand_{kind}_mono.xml", head() + fg(kind, mono=True) + "\n</vector>\n")
    write(f"mipmap-anydpi-v26/brand_{kind}.xml",
          '<?xml version="1.0" encoding="utf-8"?>\n<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
          f'    <background android:drawable="@drawable/brand_{kind}_bg" />\n'
          f'    <foreground android:drawable="@drawable/brand_{kind}_fg" />\n'
          f'    <monochrome android:drawable="@drawable/brand_{kind}_mono" />\n</adaptive-icon>\n')
    # Full logo (rounded square) for screens inside the app.
    write(f"drawable/logo_{kind}.xml", head(48) +
          f'<path android:pathData="M24,0h60a24,24 0 0 1 24,24v60a24,24 0 0 1 -24,24h-60a24,24 0 0 1 -24,-24v-60a24,24 0 0 1 24,-24z">'
          f'{grad(c1, c2)}</path>\n' +
          '<group android:scaleX="1.28" android:scaleY="1.28" android:pivotX="54" android:pivotY="54">\n' + fg(kind) + '\n</group>\n</vector>\n')

if len(sys.argv) > 1:
    def svg(kind, mask):
        c1, c2 = BRAND[kind]
        c1 = "#" + c1[3:]; c2 = "#" + c2[3:]
        body = fg(kind).replace("android:pathData", "d").replace("android:fillColor", "fill").replace(
            "android:strokeColor", "stroke").replace("android:strokeWidth", "stroke-width").replace(
            "android:strokeLineCap", "stroke-linecap").replace("android:strokeLineJoin", "stroke-linejoin").replace(
            "android:strokeAlpha", "stroke-opacity").replace("<path", "<path fill='none'", 0)
        body = body.replace('android:translateX="1.6" android:translateY="2.2"', 'transform="translate(1.6 2.2)"')
        import re
        body = re.sub(r'#([0-9A-F]{2})([0-9A-F]{6})', lambda m: f'#{m.group(2)}{m.group(1)}', body)
        body = re.sub(r'<path (?![^>]*fill=)', '<path fill="none" ', body)
        clip = '<circle cx="54" cy="54" r="40"/>' if mask == "circle" else '<rect x="10" y="10" width="88" height="88" rx="24"/>'
        return (f'<svg viewBox="0 0 108 108" width="150" height="150"><defs><linearGradient id="g{kind}{mask}" x1="0" y1="0" x2="1" y2="1">'
                f'<stop offset="0" stop-color="{c1}"/><stop offset="1" stop-color="{c2}"/></linearGradient>'
                f'<clipPath id="c{kind}{mask}">{clip}</clipPath></defs><g clip-path="url(#c{kind}{mask})">'
                f'<rect width="108" height="108" fill="url(#g{kind}{mask})"/><path d="M108,0v60a80,80 0 0 1 -80,-60z" fill="#ffffff" fill-opacity="0.08"/>'
                f'{body}</g></svg>')
    html = '<html><body style="margin:0;background:#e5e7eb;display:flex;gap:24px;padding:24px;font:14px sans-serif">'
    for kind, name in (("aircursor", "AirCursor"), ("pc", "AirCursor PC")):
        html += f'<div style="text-align:center">{svg(kind, "circle")}<br>{svg(kind, "squircle")}<br><b>{name}</b></div>'
    open(sys.argv[1], "w").write(html + "</body></html>")
print("logos written")
